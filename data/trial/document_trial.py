r"""Trial 7 - Document agent on the real certificates (local OCR text from ocr_pages.py).

eSAKSHI's Utilisation Certificate (Annexure-VI) is generated by the portal, printed, signed
and scanned back in. Its typed fields can be read without any AI service:
  implementing agency, work name and location, sanction date, sanctioned amount, the vendor
  (name + unique code), work status, payment approval dates and amounts.

Checks against the portal record of the work the file is attached to:
  1. right document   - does the certificate's amount / location belong to THIS work?
  2. bundled files    - one file carrying certificates of several different works
  3. sanction delay   - recommendation date (portal) -> sanction date (certificate); limit 75 days
  4. status           - portal says COMPLETED but the only certificate says "in progress"
  5. contractors      - vendors per implementing district authority, and their share

Bank account numbers are read by the OCR but never stored in results.

Run:  .venv-trial\Scripts\python.exe data\trial\document_trial.py
"""

from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "data" / "trial" / "cache" / "ocr"
EVID = ROOT / "data" / "evidence"
BUILD = ROOT / "data" / "build"
OUT = ROOT / "data" / "trial" / "results"
SANCTION_LIMIT = 75

VENDOR_CODE = re.compile(r"\bV\d{12}\b")
RUPEES = re.compile(r"(?:rs\.?|inr|₹|rupees)\s*:?\s*([\d,]{4,}(?:\.\d{1,2})?)|([\d,]{5,}(?:\.\d{1,2})?)\s*/-", re.I)
DATE = r"(\d{2}/\d{2}/\d{4})"


def squash(s: str) -> str:
    return re.sub(r"\s+", "", s).lower()


def ordered_lines(page: dict) -> list[dict]:
    """Boxes in reading order. Boxes whose vertical centres sit within half a line height of
    the current row join it, so a label and its value on one printed line stay together."""
    boxes = [{"x": min(p[0] for p in box), "y": min(p[1] for p in box),
              "h": max(p[1] for p in box) - min(p[1] for p in box), "text": text}
             for box, text, _ in page["lines"]]
    for b in boxes:
        b["cy"] = b["y"] + b["h"] / 2
    if not boxes:
        return []
    half = sorted(b["h"] for b in boxes)[len(boxes) // 2] / 2
    rows, current = [], []
    for b in sorted(boxes, key=lambda b: b["cy"]):
        if current and b["cy"] - sum(c["cy"] for c in current) / len(current) > half:
            rows.append(current)
            current = []
        current.append(b)
    rows.append(current)
    return [b for row in rows for b in sorted(row, key=lambda b: b["x"])]


def after_colon(label: str, lines: list[dict]) -> str | None:
    key = squash(label)
    for r in lines:
        t = r["text"]
        if squash(t).startswith(key):
            v = t.split(":", 1)[1] if ":" in t else t[len(label):]
            v = v.strip(" :")
            return v or None
    return None


def parse_uc(page: dict) -> dict | None:
    lines = ordered_lines(page)
    flat = squash(" ".join(r["text"] for r in lines))
    if "utilizationcertificate" not in flat or "nameofwork" not in flat:
        return None
    f = {"agency": after_colon("Implementing Agency", lines),
         "ida": after_colon("Implementing District Authority", lines),
         "work_name": after_colon("Name of Work", lines),
         "location": after_colon("Location of Work", lines)}
    m = re.search(r"sanctiondate.{0,40}?" + DATE, flat)
    f["sanction_date"] = m.group(1) if m else None
    m = re.search(r"totalsanctionedamountforthework:?rs\.?([\d,]+(?:\.\d+)?)", flat)
    f["sanctioned_amount"] = float(m.group(1).replace(",", "")) if m else None
    m = re.search(r"workstatus:?\(completed/?inprogress\)(completed|inprogress)", flat)
    f["status"] = m.group(1) if m else None
    m = re.search(r"paymentapprovaldate:?" + DATE, flat)
    f["payment_date"] = m.group(1) if m else None
    m = re.search(r"approvedamount:?rs\.?([\d,]+(?:\.\d+)?)", flat)
    f["approved_amount"] = float(m.group(1).replace(",", "")) if m else None
    code = next((r for r in lines if VENDOR_CODE.search(r["text"])), None)
    f["vendor_code"] = VENDOR_CODE.search(code["text"]).group(0) if code else None
    if code:  # vendor name = the text left of the code on the same row
        same_row = [r for r in lines if abs(r["cy"] - code["cy"]) < max(8, code["h"] / 2) and r["x"] < code["x"]]
        f["vendor_name"] = " ".join(r["text"] for r in sorted(same_row, key=lambda r: r["x"])).strip() or None
    else:
        f["vendor_name"] = None
    return f


def parse_uc_p2(page: dict) -> dict | None:
    """The certification paragraph repeats amount and sanction date ("Certified that out of
    Rs. X ... sanctioned on DD/MM/YYYY by ..."); the OCR sometimes drops the long sanction-date
    line on page 1, so this is the fallback."""
    flat = squash(" ".join(r["text"] for r in ordered_lines(page)))
    m = re.search(r"sanctionedon" + DATE, flat)
    if not m:
        return None
    a = re.search(r"outofrs\.?([\d,]+(?:\.\d+)?)", flat)
    return {"sanction_date": m.group(1), "amount": float(a.group(1).replace(",", "")) if a else None}


def page_kind(page: dict) -> str:
    flat = squash(" ".join(t for _, t, _ in page["lines"]))
    if "utilizationcertificate" in flat and "nameofwork" in flat:
        return "utilisation_certificate"
    if "havingbeenfullysatisfied" in flat or "grants-in-aidofmpladsscheme" in flat:
        return "utilisation_certificate_p2"
    if "completioncertificate" in flat:
        return "completion_certificate"
    if "measurementbook" in flat:
        return "measurement_book"
    if any(k in flat for k in ("taxinvoice", "invoiceno", "gstin", "billno")):
        return "bill_invoice"
    if "gpsmapcamera" in flat or re.search(r"lat[^a-z]{0,3}\d{1,2}\.\d{3,}", flat):
        return "gps_photo_page"
    if len(page["lines"]) < 5:
        return "photo_or_blank"
    return "other_or_unreadable"


def to_date(s: str | None):
    try:
        return datetime.strptime(s, "%d/%m/%Y").date() if isinstance(s, str) else None
    except (ValueError, TypeError):
        return None


def main() -> None:
    manifest = [json.loads(line) for line in (EVID / "manifest.jsonl").read_text(encoding="utf-8").splitlines()]
    file_work = {Path(f["path"].replace("\\", "/")).stem: r["work_id"] for r in manifest for f in r["files"]}
    sample_of = {r["work_id"]: r["sample"] for r in manifest}
    w = pd.read_parquet(BUILD / "works.parquet").set_index("work_id")

    pages = defaultdict(list)
    for p in sorted(CACHE.glob("*_p[0-9]*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        pages[Path(d["file"]).stem].append(d)
    kinds = Counter()
    ucs = []
    cert_pages, cert_ticked = 0, 0
    other_amounts = []
    kinds_by_sample = defaultdict(Counter)
    file_kind_by_sample = defaultdict(Counter)
    for stem, plist in pages.items():
        found, certs = [], []
        smp = sample_of.get(file_work.get(stem), "?")
        file_kinds = set()
        for d in sorted(plist, key=lambda d: d["page"]):
            k = page_kind(d)
            kinds[k] += 1
            kinds_by_sample[smp][k] += 1
            file_kinds.add(k)
        readable = file_kinds - {"other_or_unreadable", "photo_or_blank"}
        file_kind_by_sample[smp]["has_readable_page" if readable else "nothing_readable"] += 1
        for d in sorted(plist, key=lambda d: d["page"]):
            k = page_kind(d)
            text = " ".join(r["text"] for r in ordered_lines(d))
            if "havingbeenfullysatisfied" in squash(text):   # the certification paragraph
                cert_pages += 1
                cert_ticked += any(b.strip() for b in re.findall(r"\[([^\]]{0,3})\]", text))
            if k == "utilisation_certificate":
                f = parse_uc(d)
                if f:
                    found.append(f | {"file": stem, "page": d["page"], "work_id": file_work.get(stem)})
            p2 = parse_uc_p2(d)
            if p2:
                certs.append(p2)
        for f in found:  # fill a sanction date the OCR dropped from the certification paragraph
            if f["sanction_date"] is None:
                same = [c for c in certs if c["amount"] == f["sanctioned_amount"]] or (certs if len(certs) == 1 else [])
                if same:
                    f["sanction_date"], f["sanction_date_from"] = same[0]["sanction_date"], "certification"
        ucs.extend(found)
        if not found:  # any other readable paper: do the rupee amounts on it include the portal's?
            text = " ".join(" ".join(t for _, t, _ in d["lines"]) for d in plist)
            raw = [(m.group(1) or m.group(2)).replace(",", "") for m in RUPEES.finditer(text)]
            amounts = {float(a) for a in raw if re.fullmatch(r"\d+(?:\.\d{1,2})?", a)}
            amounts = {a for a in amounts if a >= 1000}
            if amounts:
                other_amounts.append({"file": stem, "work_id": file_work.get(stem), "sample": smp, "amounts": amounts})
    u = pd.DataFrame(ucs)
    res = {"files_read": len(pages), "pages_read": int(sum(kinds.values())), "page_kinds": dict(kinds.most_common()),
           "utilisation_certificates": int(len(u)),
           "certification_pages": cert_pages, "certification_pages_with_any_box_marked": int(cert_ticked),
           "page_kinds_by_sample": {s: dict(c.most_common()) for s, c in kinds_by_sample.items()},
           "pdf_files_by_sample": {s: dict(c) for s, c in file_kind_by_sample.items()}}
    if u.empty:
        print(json.dumps(res, indent=2))
        return
    parsed = {c: round(float(u[c].notna().mean()), 3) for c in
              ("agency", "work_name", "location", "sanction_date", "sanctioned_amount", "status",
               "payment_date", "approved_amount", "vendor_code", "vendor_name")}
    res["fields_read_share"] = parsed

    u = u.join(w[["amount", "description", "recommended_date", "completed_date", "status", "agency_name",
                  "district_name"]].rename(columns={"status": "portal_status"}), on="work_id")
    u["sample"] = u.work_id.map(sample_of)

    # 1 + 2: does the certificate belong to this work? The portal amount is what was PAID, so a
    # certificate belongs when its sanction covers the payment (within 10%), when one payment or
    # the file's payments together equal it, or when its location is named in the description.
    ratio = u.sanctioned_amount / u.amount
    u["amount_consistent"] = ratio.between(0.99, 1.10)
    u["approved_matches"] = (u.approved_amount - u.amount).abs() <= 1
    loc_tokens = u.location.fillna("").str.lower().str.findall(r"[a-z]{4,}")
    u["location_in_description"] = [any(t in (d or "").lower() for t in toks) if toks else False
                                    for toks, d in zip(loc_tokens, u.description)]
    u["readable"] = u.sanctioned_amount.notna() | u.location.notna()
    u["belongs"] = u.amount_consistent | u.approved_matches | u.location_in_description
    per_file = u[u.readable].groupby("file").agg(work_id=("work_id", "first"), ucs=("page", "size"),
                                                 belongs=("belongs", "sum"), sample=("sample", "first"))
    wrong = per_file[per_file.belongs == 0]
    bundled = per_file[(per_file.belongs > 0) & (per_file.belongs < per_file.ucs)]
    cols = ["work_id", "file", "page", "location", "sanctioned_amount", "approved_amount", "amount", "description"]
    res["right_document"] = {
        "files_with_certificates": int(len(per_file)),
        "files_whose_certificates_all_belong": int((per_file.belongs == per_file.ucs).sum()),
        "files_with_no_certificate_for_their_work": int(len(wrong)),
        "files_also_carrying_other_works_certificates": int(len(bundled)),
        "examples_no_certificate_for_their_work": u[u.file.isin(wrong.index)][cols].astype(str).head(15).to_dict("records"),
        "examples_other_works_certificates": u[u.file.isin(bundled.index) & ~u.belongs][cols].astype(str).head(15).to_dict("records"),
    }

    # 3: sanction delay (only certificates that belong to their work)
    own = u[u.belongs].drop_duplicates("work_id").copy()
    own["sanctioned"] = own.sanction_date.map(to_date)
    own["rec"] = pd.to_datetime(own.recommended_date).dt.date
    own["sanction_days"] = [(s - r).days if s and r else None for s, r in zip(own.sanctioned, own.rec)]
    sd = own.sanction_days.dropna()
    res["sanction_delay"] = {"works": int(len(sd)), "median_days": float(sd.median()) if len(sd) else None,
                             "over_45_days": int((sd > 45).sum()),   # if the 2023 text's 45 days applies
                             "over_75_days": int((sd > SANCTION_LIMIT).sum()),
                             "negative_days": int((sd < 0).sum()),
                             "share_over_75": round(float((sd > SANCTION_LIMIT).mean()), 3) if len(sd) else None}

    # 4: status - every one of these works is COMPLETED on the portal
    mine = u[u.belongs]
    any_completed = mine.groupby("work_id").status.agg(lambda s: bool((s == "completed").any()))
    res["status"] = {"works_with_own_certificate": int(len(any_completed)),
                     "works_whose_certificates_all_say_in_progress": int((~any_completed).sum()),
                     "certificates_by_status": mine.status.value_counts(dropna=False).to_dict()}

    # 5: contractors - the vendor unique code is an exact identity, no name matching needed
    v = mine.dropna(subset=["vendor_code"]).drop_duplicates(["work_id", "vendor_code"])
    names = v.groupby("vendor_code").vendor_name.agg(lambda s: s.dropna().mode().iloc[0] if s.notna().any() else None)
    conc = []
    for dist, g in v.groupby("district_name"):
        c = g.vendor_code.value_counts()
        if g.work_id.nunique() >= 5:
            conc.append({"district": dist, "works": int(g.work_id.nunique()), "vendors": int(len(c)),
                         "top_vendor": names.get(c.index[0]), "top_vendor_share": round(float(c.iloc[0] / c.sum()), 3),
                         "top3_share": round(float(c.iloc[:3].sum() / c.sum()), 3)})
    top = v.vendor_code.value_counts().head(10)
    agency_norm = v.agency.fillna("?").map(squash)
    res["contractors"] = {"works_with_vendor": int(v.work_id.nunique()), "distinct_vendors": int(v.vendor_code.nunique()),
                          "by_district": sorted(conc, key=lambda r: -r["works"]),
                          "top_vendors": [{"vendor": names.get(k), "works": int(n)} for k, n in top.items()],
                          "agencies": agency_norm.value_counts().head(8).to_dict(),
                          "vendors_per_agency": v.assign(a=agency_norm).groupby("a").vendor_code.nunique()
                          .sort_values(ascending=False).head(8).to_dict()}
    # other readable papers (completion certificates, bills, estimates): amount agreement
    oa = pd.DataFrame(other_amounts)
    if not oa.empty:
        portal = w.amount.reindex(oa.work_id).values
        oa["matches"] = [any(abs(a - p) <= max(1.0, 0.01 * p) for a in am) if p == p else None
                         for am, p in zip(oa.amounts, portal)]
        res["other_papers_amount_check"] = {
            s: {"files_with_rupee_amounts": int((oa["sample"] == s).sum()),
                "an_amount_equals_portal_within_1pct": int(oa[(oa["sample"] == s)].matches.fillna(False).sum())}
            for s in ("district", "national")}
    res["by_sample"] = {s: {"files": int((per_file["sample"] == s).sum()),
                            "no_certificate_for_their_work": int((wrong["sample"] == s).sum())}
                        for s in ("district", "national")}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "document_trial.json").write_text(json.dumps(res, indent=2, default=str, ensure_ascii=False),
                                             encoding="utf-8")
    print(json.dumps(res, indent=2, default=str, ensure_ascii=False))


if __name__ == "__main__":
    main()
