// Each HTML form in forms/ becomes a module exporting its markup as one string, so a signed-in page
// can show it in a frame (srcDoc) without the form being a public file anyone can open by its URL.
// The form itself is never edited: change forms/<name>.html, then run this (dev and build run it).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = "forms";
const out = "src/lib/forms";
mkdirSync(out, { recursive: true });
for (const f of readdirSync(src).filter((n) => n.endsWith(".html"))) {
  const html = readFileSync(`${src}/${f}`, "utf8");
  const name = f.replace(/\.html$/, "");
  const body =
    `// Generated by scripts/embed-forms.mjs from forms/${f}: edit the HTML, not this file.\n` +
    `const html: string = ${JSON.stringify(html)};\n\nexport default html;\n`;
  writeFileSync(`${out}/${name}.ts`, body);
  console.log("embedded form", f);
}
